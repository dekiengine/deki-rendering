/// How much of the letter's pixel (x, y) its face covers, 0 to 3.
constexpr int Cover(const Letter& letter, int x, int y)
{
    const int at = letter.first + y * letter.width + x;
    return (kLetterBits[at / 4] >> (at % 4 * 2)) & 3;
}

